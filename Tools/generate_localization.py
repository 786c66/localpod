def esc(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def main() -> None:
    data = json.loads(CATALOG.read_text())
    catalog = data["strings"]
    missing = [key for key in catalog if key not in EN]
    if missing:
        raise SystemExit("Missing English translations:\n" + "\n".join(repr(k) for k in missing))

    en_lines = ["/* English UI strings for LocalPod. */", ""]
    zh_lines = ["/* LocalPod 简体中文界面文案。 */", ""]

    for key in sorted(catalog):
        source = key
        localizations = catalog[key].get("localizations", {})
        zh_value = localizations.get("zh-Hans", {}).get("stringUnit", {}).get("value", key)
        en_lines.append(f'"{esc(key)}" = "{esc(EN[key])}";')
        # Chinese keys are already the source; still write an explicit value so
        # every entry has a concrete translation in both tables.
        if zh_value != key or key not in SEMANTIC_ZH:
            zh_lines.append(f'"{esc(key)}" = "{esc(zh_value)}";')

    for key in sorted(SEMANTIC_ZH):
        zh_lines.append(f'"{esc(key)}" = "{esc(SEMANTIC_ZH[key])}";')
        en_lines.append(f'"{esc(key)}" = "{esc(SEMANTIC_EN[key])}";')

    (ROOT / "LocalPod/Resources/en.lproj/Localizable.strings").write_text(
        "\n".join(en_lines) + "\n"
    )
    (ROOT / "LocalPod/Resources/zh-Hans.lproj/Localizable.strings").write_text(
        "\n".join(zh_lines) + "\n"
    )
    print(f"Wrote {len(catalog)} extracted keys and {len(SEMANTIC_ZH)} semantic keys")


if __name__ == "__main__":
    main()
